/**
 * Generates src/app/tokens/breakpoints.css from src/lib/layout/breakpoints.ts,
 * so the scale is defined once and the custom properties cannot drift from the
 * TypeScript helpers.
 *
 * Imports a .ts module directly, which relies on Node's type stripping
 * (Node >= 22.18). Run: npm run generate-breakpoint-tokens
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BREAKPOINTS, BREAKPOINT_NOTES } from '../src/lib/layout/breakpoints.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '../src/app/tokens/breakpoints.css');

const entries = Object.entries(BREAKPOINTS);
const labels = entries.map(([name, px]) => `${name} (${px}):`);
const pad = Math.max(...labels.map((label) => label.length)) + 1;

const doc = entries
  .map(([name], i) => ` * ${labels[i].padEnd(pad)}${BREAKPOINT_NOTES[name]}`)
  .join('\n');

const vars = entries.map(([name, px]) => `    --bp-${name}: ${px}px;`).join('\n');

const css = `/*
 * GENERATED by scripts/generate-breakpoint-tokens.mjs, do not edit by hand.
 * The scale lives in src/lib/layout/breakpoints.ts.
 *
 * These custom properties document the scale for stylesheets. Media queries
 * still need literal px values, custom properties are not valid inside @media:
 * see the @custom-media note in the README before repeating a number.
 *
${doc}
 */
@layer base {
  :root {
${vars}
  }
}
`;

writeFileSync(OUT, css);
console.log(`Wrote ${entries.length} breakpoints to ${OUT}`);
