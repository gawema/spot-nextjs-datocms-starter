/**
 * Generates src/app/tokens/fluid.css from src/lib/layout/fluidScale.ts, Utopia
 * style: every token interpolates linearly between its size at FLUID_MIN_VW and
 * its size at the top breakpoint, so nothing needs a media query to grow.
 *
 * Imports .ts modules directly, which relies on Node's type stripping
 * (Node >= 22.18). Run: npm run generate-fluid-tokens
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BREAKPOINTS } from '../src/lib/layout/breakpoints.ts';
import {
  FLUID_FONT_SIZES,
  FLUID_MAX_ROOT_REM,
  FLUID_MIN_VW,
  FLUID_ROOT_PX,
  FLUID_SPACING,
} from '../src/lib/layout/fluidScale.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '../src/app/tokens/fluid.css');

const MAX_VW = BREAKPOINTS['3xl'];

/**
 * Utopia clamp: linear interpolation between minPx@FLUID_MIN_VW and maxPx@MAX_VW.
 * @param {number} minPx
 * @param {number} maxPx
 */
function fluidClamp(minPx, maxPx) {
  const slope = (maxPx - minPx) / (MAX_VW - FLUID_MIN_VW);
  const interceptRem = round((minPx - slope * FLUID_MIN_VW) / FLUID_ROOT_PX);
  return `clamp(${round(minPx / FLUID_ROOT_PX)}rem, ${interceptRem}rem + ${round(slope * 100)}vw, ${round(maxPx / FLUID_ROOT_PX)}rem)`;
}

/** @param {number} n */
function round(n) {
  return Math.round(n * 10000) / 10000;
}

/** @param {import('../src/lib/layout/fluidScale.ts').FluidToken} token */
function declaration({ name, minPx, maxPx, role }) {
  const note = role ? `${minPx}px→${maxPx}px, ${role}` : `${minPx}px→${maxPx}px`;
  return `    ${name}: ${fluidClamp(minPx, maxPx)}; /* ${note} */`;
}

const css = `/* AUTO-GENERATED by scripts/generate-fluid-tokens.mjs, do not edit by hand */
@layer base {
  :root {
    --fluid-min-vw: ${FLUID_MIN_VW};
    --fluid-max-vw: ${MAX_VW};

${FLUID_FONT_SIZES.map(declaration).join('\n')}

${FLUID_SPACING.map(declaration).join('\n')}
  }

  /*
   * Past the design range every clamp is pegged to its maximum, so the page
   * keeps stretching while the type stays put and the content looks lost on a
   * wide screen. Scaling the root instead keeps the whole rem-based system in
   * proportion. The max() is there so a visitor who raised their own browser
   * font size never has it scaled back down.
   */
  @media (min-width: ${MAX_VW + 1}px) {
    html {
      font-size: max(1rem, min(100vw / ${MAX_VW / FLUID_ROOT_PX}, ${FLUID_MAX_ROOT_REM}rem));
    }
  }
}
`;

writeFileSync(OUT, css, 'utf8');
console.log(`Wrote ${FLUID_FONT_SIZES.length + FLUID_SPACING.length} fluid tokens to ${OUT}`);
