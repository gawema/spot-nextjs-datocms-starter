/**
 * Generates the fluid clamp() tokens in src/app/tokens/fluid.css, Utopia style:
 * every token interpolates linearly between its size at 375px and its size at
 * 1920px, so nothing needs a media query to grow.
 *
 * Edit FLUID_TOKENS, then run: npm run generate-fluid-tokens
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '../src/app/tokens/fluid.css');

const MIN_VW = 375;
const MAX_VW = 1920;
const ROOT_PX = 16;

/** @typedef {{ name: string; minPx: number; maxPx: number; comment?: string }} FluidToken */

/** @type {FluidToken[]} */
const FLUID_TOKENS = [
  // Headings. Body copy stays static, see primitives.css.
  { name: '--font-size-display', minPx: 48, maxPx: 80, comment: 'hero / display' },
  { name: '--font-size-h1', minPx: 36, maxPx: 56 },
  { name: '--font-size-h2', minPx: 28, maxPx: 40 },
  { name: '--font-size-h3', minPx: 24, maxPx: 30 },
  { name: '--font-size-h4', minPx: 20, maxPx: 24 },
  { name: '--font-size-h5', minPx: 18, maxPx: 20 },

  // Vertical rhythm: the space a section puts above and below itself.
  { name: '--padding-vertical-small', minPx: 24, maxPx: 32 },
  { name: '--padding-vertical-main', minPx: 48, maxPx: 64 },
  { name: '--padding-vertical-large', minPx: 96, maxPx: 128 },
  { name: '--padding-vertical-xl', minPx: 128, maxPx: 192 },

  // Horizontal gutters.
  { name: '--padding-horizontal-padding-global', minPx: 16, maxPx: 24 },
  { name: '--padding-horizontal-container-gutter', minPx: 16, maxPx: 24 },
  { name: '--viewport-grid-gutter', minPx: 12, maxPx: 16 },
];

/**
 * Utopia clamp: linear interpolation between minPx@MIN_VW and maxPx@MAX_VW.
 * @param {number} minPx
 * @param {number} maxPx
 */
function fluidClamp(minPx, maxPx) {
  const minRem = round(minPx / ROOT_PX);
  const maxRem = round(maxPx / ROOT_PX);
  const slope = (maxPx - minPx) / (MAX_VW - MIN_VW);
  const interceptRem = round((minPx - slope * MIN_VW) / ROOT_PX);
  const vwCoeff = round(slope * 100);
  return `clamp(${minRem}rem, ${interceptRem}rem + ${vwCoeff}vw, ${maxRem}rem)`;
}

/** @param {number} n */
function round(n) {
  return Math.round(n * 10000) / 10000;
}

const lines = [
  '/* AUTO-GENERATED by scripts/generate-fluid-tokens.mjs, do not edit by hand */',
  '@layer base {',
  '  :root {',
  `    --fluid-min-vw: ${MIN_VW};`,
  `    --fluid-max-vw: ${MAX_VW};`,
  '',
];

for (const token of FLUID_TOKENS) {
  const comment = token.comment
    ? ` /* ${token.minPx}px→${token.maxPx}px, ${token.comment} */`
    : ` /* ${token.minPx}px→${token.maxPx}px */`;
  lines.push(`    ${token.name}: ${fluidClamp(token.minPx, token.maxPx)};${comment}`);
}

lines.push(
  '',
  '    /* The gap between two sections tracks the largest vertical rhythm step. */',
  '    --section-stack-gap: var(--padding-vertical-xl);',
  '  }',
  '}',
  '',
);

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`Wrote ${FLUID_TOKENS.length} fluid tokens to ${OUT}`);
